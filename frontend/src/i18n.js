/* i18n.js -- interface language support for SchemeSetu.
 *
 * Scope: this translates the INTERFACE (buttons, labels, errors). Chat answers
 * are translated by the backend (translate-first pipeline in rag_chat.py), and
 * scheme cards in a single batched POST /translate/batch.
 *
 * Any key missing from a language falls back to English, so a gap never shows
 * a blank label. Translations were drafted with AI assistance: have a native
 * speaker skim them before a public demo.
 */

import { EXTRA } from "./i18n_extra";

export const DEFAULT_LANG = "en";
const STORAGE_KEY = "schemesetu_lang";

/* `speech` is the BCP-47 tag for read-aloud; `listen` (optional) overrides it for
   speech recognition. Punjabi needs the explicit Gurmukhi tag "pa-Guru-IN" or the
   recognizer can return the wrong script. */
export const LANGUAGES = [
  { code: "en", native: "English", speech: "en-IN" },
  { code: "hi", native: "हिन्दी", speech: "hi-IN" },
  { code: "ta", native: "தமிழ்", speech: "ta-IN" },
  { code: "te", native: "తెలుగు", speech: "te-IN" },
  { code: "kn", native: "ಕನ್ನಡ", speech: "kn-IN" },
  { code: "ml", native: "മലയാളം", speech: "ml-IN" },
  { code: "mr", native: "मराठी", speech: "mr-IN" },
  { code: "bn", native: "বাংলা", speech: "bn-IN" },
  { code: "gu", native: "ગુજરાતી", speech: "gu-IN" },
  { code: "pa", native: "ਪੰਜਾਬੀ", speech: "pa-IN", listen: "pa-Guru-IN" },
];

export function languageInfo(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function loadSavedLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGUAGES.some((l) => l.code === saved)) return saved;
  } catch {
    /* storage can be blocked; fall through */
  }
  return DEFAULT_LANG;
}

export function saveLanguage(code) {
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    /* ignore */
  }
}

